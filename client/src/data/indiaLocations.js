/**
 * Helper to get cities for a state
 */
export const getCitiesForState = (stateName) => {
  return INDIA_CITIES_BY_STATE[stateName] || [];
};

/**
 * Helper to find coordinates for a selected state & city
 */
export const findCoordinatesForCity = (stateName, cityName) => {
  const cities = INDIA_CITIES_BY_STATE[stateName];
  if (!cities) return { lat: 18.5204, lng: 73.8567 }; // Default fallback

  const match = cities.find(
    (c) => c.name.toLowerCase() === (cityName || '').toLowerCase() ||
           c.name.toLowerCase().includes((cityName || '').toLowerCase())
  );

  return match ? { lat: match.lat, lng: match.lng } : { lat: cities[0]?.lat || 18.5204, lng: cities[0]?.lng || 73.8567 };
};
